// Atlas layout: 16 chars wide × 6 rows = 96 chars, each 8×8 px → 128×48 px.
static constexpr int kAtlasW   = 128;
static constexpr int kAtlasH   =  48;
static constexpr int kCols     =  16;
static constexpr int kRows     =   6;
static constexpr float kInvW   = 1.0f / kAtlasW;
static constexpr float kInvH   = 1.0f / kAtlasH;

// ── Font ─────────────────────────────────────────────────────────────────────

Font::~Font() {
    if (tex_) glDeleteTextures(1, &tex_);
    if (vbo_) glDeleteBuffers(1, &vbo_);
    if (vao_) glDeleteVertexArrays(1, &vao_);
}

void Font::buildAtlas() {
    uint8_t pixels[kAtlasH][kAtlasW] = {};
    for (int g = 0; g < 96; ++g) {
        int charCol = g % kCols;
        int charRow = g / kCols;
        for (int row = 0; row < 8; ++row) {
            uint8_t bits = kGlyph[g][row];
            for (int col = 0; col < 8; ++col) {
                int px = charCol * 8 + col;
                int py = charRow * 8 + row;
                pixels[py][px] = (bits & (1u << col)) ? 0xFF : 0x00;
            }
        }
    }

    glGenTextures(1, &tex_);
    glBindTexture(GL_TEXTURE_2D, tex_);
    glPixelStorei(GL_UNPACK_ALIGNMENT, 1);
    glTexImage2D(GL_TEXTURE_2D, 0, GL_R8,
                 kAtlasW, kAtlasH, 0,
                 GL_RED, GL_UNSIGNED_BYTE, pixels);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MIN_FILTER, GL_NEAREST);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MAG_FILTER, GL_NEAREST);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_WRAP_S, GL_CLAMP_TO_EDGE);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_WRAP_T, GL_CLAMP_TO_EDGE);
    glBindTexture(GL_TEXTURE_2D, 0);
}

bool Font::init(const std::string& shaderDir) {
    if (!sh_.loadFromFiles(shaderDir + "/text.vert", shaderDir + "/text.frag"))
        return false;

    buildAtlas();

    glGenVertexArrays(1, &vao_);
    glGenBuffers(1, &vbo_);
    glBindVertexArray(vao_);
    glBindBuffer(GL_ARRAY_BUFFER, vbo_);
    // Preallocate for up to 256 chars (6 verts × 4 floats per char).
    glBufferData(GL_ARRAY_BUFFER, 256 * 6 * 4 * sizeof(float), nullptr, GL_DYNAMIC_DRAW);
    glEnableVertexAttribArray(0);
    glVertexAttribPointer(0, 2, GL_FLOAT, GL_FALSE, 4 * sizeof(float), (void*)0);
    glEnableVertexAttribArray(1);
    glVertexAttribPointer(1, 2, GL_FLOAT, GL_FALSE, 4 * sizeof(float), (void*)(2 * sizeof(float)));
    glBindVertexArray(0);

    sh_.use();
    sh_.setInt("uFont", 0);

    return true;
}

void Font::draw(const std::string& text, float x, float y,
                float charW, float charH, const glm::vec4& color) {
    if (text.empty()) return;

    verts_.clear();
    verts_.reserve(text.size() * 6 * 4);

    float cx = x;
    for (unsigned char ch : text) {
        if (ch < 0x20 || ch > 0x7F) { cx += charW; continue; }
        int idx = ch - 0x20;
        int gcol = idx % kCols;
        int grow = idx / kCols;

        float u0 = gcol * 8 * kInvW;
        float u1 = u0 + 8 * kInvW;
        float v0 = grow * 8 * kInvH;
        float v1 = v0  + 8 * kInvH;

        float x0 = cx,        y0 = y;          // top-left
        float x1 = cx + charW, y1 = y - charH; // bottom-right (NDC y down)

        // Triangle 1
        verts_.insert(verts_.end(), { x0,y0, u0,v0,  x1,y0, u1,v0,  x1,y1, u1,v1 });
        // Triangle 2
        verts_.insert(verts_.end(), { x0,y0, u0,v0,  x1,y1, u1,v1,  x0,y1, u0,v1 });

        cx += charW;
    }

    glBindBuffer(GL_ARRAY_BUFFER, vbo_);
    glBufferSubData(GL_ARRAY_BUFFER, 0,
                    GLsizeiptr(verts_.size() * sizeof(float)), verts_.data());

    sh_.use();
    sh_.setVec4("uColor", color);

    glActiveTexture(GL_TEXTURE0);
    glBindTexture(GL_TEXTURE_2D, tex_);

    glBindVertexArray(vao_);
    glDrawArrays(GL_TRIANGLES, 0, GLsizei(text.size() * 6));
    glBindVertexArray(0);
}

void Font::drawShadowed(const std::string& text, float x, float y,
                        float charW, float charH, const glm::vec4& color) {
    float ox = charW * 0.10f;
    float oy = charH * 0.10f;
    draw(text, x + ox, y - oy, charW, charH, { 0.0f, 0.0f, 0.0f, color.a * 0.75f });
    draw(text, x,      y,      charW, charH, color);
}
